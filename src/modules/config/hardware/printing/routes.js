const {Router}=require('express')
const {Auth}=require('../../../../middlewares/autenticacion')
const {prisma,prismaTransaction}=require('../../../../models/prisma')
const {handler,scope}=require('../controller')
const {resolveWorkstation}=require('../operations')
const router=Router()
router.use(Auth)
router.get('/workstation',handler((r,s)=>resolveWorkstation(prisma,s,r.query)))
const jobs=require('./service')
const {measureRequestPhase}=require('../../../../utils/requestTiming')
router.post('/print-jobs',handler((r,s)=>measureRequestPhase(r,'ticket_snapshot',()=>jobs.createJob(prismaTransaction,s,r.body,require('./validation').documentOptions(r.query))),201))
router.get('/print-jobs/:id',handler((r,s)=>jobs.getJob(prisma,s,r.params.id)))
router.get('/print-jobs/:id/document',handler((r,s)=>jobs.jobDocument(prisma,s,r.params.id)))
router.get('/print-jobs/:id/logo',async(req,res,next)=>{try{const logo=await jobs.jobLogo(prisma,scope(req),req.params.id);res.setHeader('Content-Type',logo.contentType);res.setHeader('Cache-Control','private, no-store');res.send(logo.buffer)}catch(e){if(e.status)return res.status(e.status).json({message:e.message});next(e)}})
router.post('/print-jobs/:id/events',handler((r,s)=>jobs.recordEvent(prismaTransaction,s,r.params.id,r.body)))
router.post('/print-jobs/:id/download-request',handler((r,s)=>measureRequestPhase(r,'ticket_events',()=>jobs.recordPreparedDownload(prismaTransaction,s,r.params.id,r.body))))
router.post('/print-jobs/:id/reprints',handler((r,s)=>jobs.reprintJob(prismaTransaction,s,r.params.id,r.body),201))
module.exports=router
