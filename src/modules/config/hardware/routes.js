const {Router}=require('express'),{Auth,hasPermission}=require('../../../middlewares/autenticacion'),c=require('./controller')
const router=Router()
router.use(Auth,hasPermission('hardware.view'))
router.get('/workspace',c.workspace)
router.post('/workstations',hasPermission('hardware.manage'),c.createWorkstation)
router.patch('/workstations/:id',hasPermission('hardware.manage'),c.updateWorkstation)
router.post('/devices',hasPermission('hardware.manage'),c.createDevice)
router.patch('/devices/:id',hasPermission('hardware.manage'),c.updateDevice)
router.put('/workstations/:id/assignments',hasPermission('hardware.manage'),c.assignDevices)
router.post('/tests',c.recordTest)
router.get('/tests',c.tests)
router.get('/history',c.history)
router.get('/print-jobs',c.handler((r,s)=>require('./printing/service').printHistory(require('../../../models/prisma').prisma,s,r.query)))
router.get('/drawer-policy',c.handler((r,s)=>require('./drawer/policy').readPolicy(require('../../../models/prisma').prisma,s,true)))
router.put('/drawer-policy',hasPermission('hardware.manage'),c.handler((r,s)=>require('./drawer/policy').savePolicy(require('../../../models/prisma').prismaTransaction,s,r.body)))
module.exports=router
