const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto')
const {withAppointmentsTestDb,seedAgenda}=require('./helpers/appointmentsTestDb.cjs')
const {activityInput}=require('./helpers/agendaActivityFixture.cjs')
const activity=()=>require('../src/modules/appointments/activities')
const update=(f,row,patch={})=>({...activityInput(f),...patch,expectedVersion:row.version,reason:'Cambio solicitado',idempotencyKey:crypto.randomUUID()})
test('reunión sin catálogo ni contactos es idempotente y no crea operaciones comerciales',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  // Explicitly disable the integrations, not merely remove their data.
  for(const module_code of ['inventory','contacts','hr']) await db.companyModule.create({data:{company_id:scope.companyId,module_code,status:'DISABLED'}})
  const input=activityInput(f,{userIds:[f.userId],guests:[{name:'Invitada externa',contactId:null}]})
  const row=await activity().createActivity(db,scope,input)
  assert.equal(row.recordType,'ACTIVITY');assert.equal(row.productId,null)
  assert.equal((await activity().createActivity(db,scope,input)).id,row.id)
  assert.equal(await db.appointmentBooking.count(),0);assert.equal(await db.sale.count(),0)
  assert.equal(await db.appointmentParticipant.count(),2);assert.equal(await db.appointmentHistory.count(),1)
  assert.deepEqual(row.participants,[{id:f.userId,name:'Recepción QA'}])
  assert.equal(JSON.stringify(row.participants).includes('@'),false)
  await assert.rejects(()=>activity().createActivity(db,scope,{...input,title:'Otro envío'}),{code:'IDEMPOTENCY_CONFLICT'})
  assert.equal(await db.appointmentSession.count(),1)
  await assert.rejects(()=>activity().createActivity(db,scope,{...input,price:10}),{status:400})
  const users=await activity().listActivityUsers(db,scope,{q:'Recepción',page:'1'})
  assert.deepEqual(Object.keys(users.items[0]).sort(),['id','name','photoUrl'])
}))
test('edición valida versión, tenant y asignaciones antes de reemplazarlas',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  const row=await activity().createActivity(db,scope,activityInput(f,{guests:[{name:'Original',contactId:null}]}))
  const other=await db.company.create({data:{name:'Ajena QA',code:crypto.randomUUID().slice(0,16)}})
  await db.companyModule.create({data:{company_id:other.id,module_code:'appointments',status:'ACTIVE'}})
  await assert.rejects(()=>activity().getActivity(db,{...scope,companyId:other.id},row.id),{status:404})
  await assert.rejects(()=>activity().updateActivity(db,scope,row.id,update(f,row,{organizerId:crypto.randomUUID()})),{status:400})
  assert.equal((await activity().getActivity(db,scope,row.id)).guests[0].name,'Original')
  assert.equal(await db.appointmentHistory.count(),1)
  const changed=await activity().updateActivity(db,scope,row.id,update(f,row,{title:'Reunión actualizada'}))
  assert.equal(changed.version,2)
  await assert.rejects(()=>activity().updateActivity(db,scope,row.id,update(f,row)),{code:'STALE_VERSION'})
  await db.userCompany.delete({where:{user_id_company_id:{user_id:f.userId,company_id:scope.companyId}}})
  assert.equal((await activity().getActivity(db,scope,row.id)).organizerId,f.userId)
  await assert.rejects(()=>activity().updateActivity(db,scope,row.id,update(f,changed)),{status:400})
  assert.equal(await db.appointmentHistory.count(),2)
}))
test('estados libres no aceptan endpoints legacy y cancelación libera personal',async()=>withAppointmentsTestDb(async context=>{
  await seedAgenda(context)
  const {db,scope,fixtures:f}=context,app=require('../src/modules/appointments/application')
  const row=await activity().createActivity(db,scope,activityInput(f))
  const transition={action:'START',expectedVersion:1,reason:'',idempotencyKey:crypto.randomUUID()}
  await assert.rejects(()=>activity().transitionActivity(db,scope,row.id,transition),{code:'TOO_EARLY'})
  await assert.rejects(()=>app.transitionSession(db,scope,row.id,transition),{status:404})
  await assert.rejects(()=>activity().getActivity(db,scope,f.groupSessionId),{status:404})
  const cancelled=await activity().transitionActivity(db,scope,row.id,{...transition,action:'CANCEL',reason:'Cancelada por organizador',idempotencyKey:crypto.randomUUID()})
  assert.equal(cancelled.status,'CANCELLED')
  await app.createBooking(db,scope,f.individualInput)
  await assert.rejects(()=>activity().updateActivity(db,scope,row.id,update(f,cancelled)),{code:'ACTIVITY_CLOSED'})
}))
test('finalización conserva el intervalo y edición sin permiso no borra notas privadas',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  const row=await activity().createActivity(db,scope,activityInput(f,{startsAt:new Date(Date.now()-60000).toISOString(),endsAt:new Date(Date.now()+3600000).toISOString(),notes:'Nota privada'}))
  const own={...scope,isAdmin:false,permissions:['appointments.view','appointments.edit','appointments.create']}
  const changed=await activity().updateActivity(db,own,row.id,update(f,row,{startsAt:row.startsAt,endsAt:row.endsAt,notes:''}))
  assert.equal(changed.notes,null)
  assert.equal((await activity().getActivity(db,scope,row.id)).notes,'Nota privada')
  const started=await activity().transitionActivity(db,scope,row.id,{action:'START',expectedVersion:2,reason:'',idempotencyKey:crypto.randomUUID()})
  const completed=await activity().transitionActivity(db,scope,row.id,{action:'COMPLETE',expectedVersion:started.version,reason:'',idempotencyKey:crypto.randomUUID()})
  assert.equal(completed.occupiedUntil,row.occupiedUntil)
  await assert.rejects(()=>activity().createActivity(db,scope,activityInput(f,{startsAt:row.startsAt,endsAt:row.endsAt})),{code:'SCHEDULE_CONFLICT'})
}))
