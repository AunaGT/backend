const test=require('node:test'),assert=require('node:assert/strict')
const {scenarioData}=require('../src/modules/config/documentTemplates/previews')
const {requestPreview,getPreview}=require('../src/modules/config/documentTemplates/previews')
const {templateDb}=require('./helpers/documentTemplateHarness.cjs')
const {resolveBase}=require('../src/modules/config/documentTemplates/public')
const {randomUUID}=require('node:crypto')
test('preflight scenarios are generated by the server, contain no real customer, and fiscal fixtures cannot masquerade as real',()=>{
  assert.equal(scenarioData('SHORT').lines.length,1)
  assert.equal(scenarioData('LONG').lines.length,200)
  assert.equal(scenarioData('LONG_TEXT').lines.length,20)
  assert.throws(()=>scenarioData('CLIENT_SUPPLIED'),{status:400})
  const data=scenarioData('SHORT','FEL_INVOICE');assert.equal(data.fiscal.fixture,true);assert.match(data.notices.join(' '),/SIN VALIDEZ FISCAL/)
})
test('real-sale preview retains its source and rechecks sale access on every later read',async()=>{
  const db=templateDb(),companyId=randomUUID(),branchId=randomUUID(),actorId=randomUUID(),saleId=randomUUID()
  const scope={companyId,branchId,actorId,permissions:['document_templates.manage','sales.view']};let allowed=true,snapshot
  db.sale={findFirst:async({where})=>allowed&&where.id===saleId&&where.branch_id===branchId?{id:saleId,created_by:actorId,reference:'V-1',date:new Date(),total:'1',subtotal:'1',discount_total:'0',sale_items:[{item_name:'Café',qty:'1',price:'1',net_total:'1',unit_metadata_version:2,unit_snapshot:{version:2,baseUnit:{label:'ud'},presentation:null}}],branch:{name:'Principal',company:{name:'Empresa'}}}:null}
  db.documentSnapshot={create:async({data})=>(snapshot={id:randomUUID(),...data})}
  db.documentArtifact={create:async({data})=>({id:randomUUID(),...data}),findFirst:async()=>({id:randomUUID(),snapshot_id:snapshot.id,format:'LETTER',state:'QUEUED',snapshot})}
  await requestPreview(db,scope,{design:resolveBase(),saleId,requestKey:'source-preview'})
  assert.equal(snapshot.branding.previewSaleId,saleId)
  const artifactId=randomUUID();assert.equal((await getPreview(db,scope,artifactId)).state,'QUEUED')
  allowed=false;await assert.rejects(getPreview(db,scope,artifactId),{status:404})
  allowed=true;await assert.rejects(getPreview(db,{...scope,branchId:randomUUID()},artifactId),{status:404})
  await assert.rejects(getPreview(db,{...scope,permissions:['document_templates.manage']},artifactId),{status:403})
  delete snapshot.branding.previewSaleId
  await assert.rejects(getPreview(db,scope,artifactId),{status:404})
})
