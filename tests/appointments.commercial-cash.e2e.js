test('active accounting posts a real advance once, and two re-post attempts share the original source',async()=>withCommercialAgendaTestDb(async({db,scope,fixtures:f})=>{
  const accounts=await configure(db,scope)
  const e=await createEngagement(db,scope,{quoteId:f.quoteId,idempotencyKey:crypto.randomUUID()})
  const received=await collectEngagementPayment(db,scope,e.id,payment(f,e))
  const {postEngagementMovement}=require('../src/services/accounting/engagementPosting')
  const entries=await Promise.all([1,2].map(()=>db.$transaction(tx=>postEngagementMovement(tx,scope,{kind:'RECEIVE',id:received.receiptId}))))
  assert.equal(entries[0],entries[1])
  const posted=await db.journalEntry.findMany({where:{source_type:'CUSTOMER_ADVANCE',source_id:received.receiptId},include:{lines:true}})
  assert.equal(posted.length,1)
  assert.deepEqual(posted[0].lines.map(l=>[l.account_id,l.debit.toFixed(2),l.credit.toFixed(2)]).sort(),[[accounts.bank.id,'40.00','0.00'],[accounts.customerAdvances.id,'0.00','40.00']].sort())
  assert.equal(await db.journalEntry.count({where:{source_type:'SALE_PAYMENT',source_id:received.receiptId}}),0)
}))
