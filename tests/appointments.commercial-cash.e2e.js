test('cash received in turn A is not counted again when a prepaid sale is created in turn B',async()=>withCommercialAgendaTestDb(async({db,scope,fixtures:f})=>{
  await configure(db,scope)
  await db.product.update({where:{id:f.productId},data:{price:40}})
  const cash=await db.paymentMethod.create({data:{name:'Efectivo'}}),register=await db.cashRegister.create({data:{branch_id:scope.branchId,name:'Caja QA',code:'QA'}})
  const turnA=await openTurn(db,scope,register.id),e=await createEngagement(db,scope,{contactId:f.contactId,lines:[{productId:f.productId,quantity:'1'}],idempotencyKey:crypto.randomUUID()})
  const received=await collectEngagementPayment(db,scope,e.id,{...payment(f,e),paymentMethodId:cash.id,cashRegisterSessionId:turnA.id})
  await db.cashRegisterSession.update({where:{id:turnA.id},data:{status:'CLOSED',closed_at:new Date()}})
  const turnB=await openTurn(db,scope,register.id)
  const sale=await db.sale.create({data:{branch_id:scope.branchId,customer_contact_id:f.contactId,total:40,adjusted_total:40,items:1,payment_method_id:cash.id,status_id:f.saleStatus.id,settlement_source:'ENGAGEMENT_RECEIPTS',cash_register_session_id:turnB.id,created_by:scope.userId}})
  const linked=await db.appointmentEngagement.update({where:{id:e.id},data:{sale_id:sale.id}})
  await db.$transaction(tx=>require('../src/modules/receivables').applyEngagementCommitments(tx,scope,linked,sale))
  await db.cashRegisterSession.update({where:{id:turnB.id},data:{status:'CLOSED',closed_at:new Date()}})
  assert.equal((await theoretical(db,scope,turnA)).theoretical.net_total,40)
  assert.equal((await theoretical(db,scope,turnB)).theoretical.net_total,0)
  assert.equal(await db.journalEntry.count({where:{source_type:'CUSTOMER_ADVANCE',source_id:received.receiptId}}),1)
}))
