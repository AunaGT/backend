const test=require('node:test'),assert=require('node:assert/strict')
const {fixture,scope,input,BRANCH}=require('./helpers/integrationsDb')
const {parseCreateInput}=require('../src/modules/integrations/credentials')
const {createCredential,getCredential,revokeCredential,replaceCredential}=require('../src/modules/integrations/management')
const {authenticateIntegration}=require('../src/modules/integrations/auth')
const {revalidateDraftContext}=require('../src/modules/integrations/policy')
const now=new Date('2026-10-25T12:00:00Z')
test('unlimited expiry is explicit null, never a missing/default/invalid number',()=>{
 assert.equal(parseCreateInput({...input,days:null}).days,null)
 const {days,...withoutDays}=input;assert.equal(parseCreateInput(withoutDays).days,90)
 for(const days of [0,-1,366,1.5,'never','90',false,'',NaN])assert.throws(()=>parseCreateInput({...input,days}),{status:400})
})
test('non-expiring credentials remain active but revoke and fresh membership still apply',async()=>{
 const f=fixture(),created=await createCredential(f.db,scope,{...input,days:null,scopes:['quotes.create_draft']},now),future=new Date('2036-10-25T12:00:00Z')
 assert.equal(f.rows[0].expires_at,null);assert.equal(created.credential.expiresAt,null);assert.equal(created.credential.status,'ACTIVE')
 const ctx=await authenticateIntegration(f.db,'Bearer '+created.apiKey,future)
 assert.equal((await revalidateDraftContext(f.db,ctx,'QUOTE',BRANCH,future)).credentialId,created.credential.id)
 assert.equal((await getCredential(f.db,scope,created.credential.id,future)).status,'ACTIVE')
 const activeMembership=f.db.userCompany.findUnique
 f.db.userCompany.findUnique=async()=>({status:'SUSPENDED',company:{active:true}})
 await assert.rejects(()=>authenticateIntegration(f.db,'Bearer '+created.apiKey,future),{status:401})
 await assert.rejects(()=>revokeCredential(f.db,scope,created.credential.id,now),{status:401})
 f.db.userCompany.findUnique=activeMembership
 await revokeCredential(f.db,scope,created.credential.id,now)
 await assert.rejects(()=>authenticateIntegration(f.db,'Bearer '+created.apiKey,future),{status:401})
})
test('bounded expiry remains exact, rejects at the deadline, and replacement does not change old expiry',async()=>{
 const f=fixture(),a=await createCredential(f.db,scope,{...input,days:7},now),deadline=new Date('2026-11-01T12:00:00Z')
 assert.equal(a.credential.expiresAt,deadline.toISOString())
 const b=await replaceCredential(f.db,scope,a.credential.id,{...input,days:null},now)
 assert.equal(b.credential.integrationId,a.credential.integrationId);assert.equal(b.credential.expiresAt,null)
 assert.equal(f.rows[0].expires_at.toISOString(),deadline.toISOString())
 await assert.rejects(()=>authenticateIntegration(f.db,'Bearer '+a.apiKey,deadline),{status:401})
 assert.equal((await authenticateIntegration(f.db,'Bearer '+b.apiKey,deadline)).credentialId,b.credential.id)
})
test('unlimited credentials count towards the same twenty-active-key ceiling',async()=>{
 const f=fixture(),out=await Promise.allSettled(Array.from({length:21},()=>createCredential(f.db,scope,{...input,days:null},now)))
 assert.equal(out.filter(r=>r.status==='fulfilled').length,20)
 assert.equal(out.find(r=>r.status==='rejected').reason.integrationCode,'KEY_LIMIT')
})
