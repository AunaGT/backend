const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto')
const {withAppointmentsTestDb,seedAgenda}=require('./helpers/appointmentsTestDb.cjs')
const app=require('../src/modules/appointments/application'),{getBooking}=require('../src/modules/appointments/queries')
test('programación manual usa zona operativa de sucursal sin permisos de configuración',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  await seedAgenda({db,scope,fixtures:f})
  await db.scheduleCalendar.updateMany({where:{company_id:scope.companyId,branch_id:scope.branchId},data:{timezone:'America/New_York'}})
  await db.serviceScheduleProfile.updateMany({where:{product_id:f.productId},data:{requires_provider:false,requires_resource:false}})
  const own={...scope,isAdmin:false,permissions:['appointments.view','appointments.create','products.view','contacts.clients.view']}
  const {listDirectory}=require('../src/modules/appointments/directory')
  const directory=await listDirectory(db,own)
  assert.equal(directory.timezone,'America/New_York')
  const row=await app.createBooking(db,own,{...f.individualInput,providerIds:[],timezone:directory.timezone})
  assert.equal(row.timezone,'America/New_York')
}))
test('reserva manual funciona en alcance propio y no inventa disponibilidad',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  await seedAgenda({db,scope,fixtures:f})
  await db.serviceScheduleProfile.updateMany({where:{product_id:f.productId},data:{requires_provider:false,duration_policy:'EDITABLE'}})
  const own={...scope,isAdmin:false,permissions:['appointments.view','appointments.create','products.view','contacts.clients.view']}
  const input={...f.individualInput,providerIds:[],endsAt:new Date(new Date(f.individualInput.startsAt).getTime()+90*60000).toISOString()}
  const row=await app.createBooking(db,own,input)
  await db.supplier.update({where:{id:f.contactId},data:{address:'Dirección QA'}})
  const {listContacts}=require('../src/modules/appointments/queries')
  assert.equal((await listContacts(db,own)).items[0].address,'Dirección QA')
  assert.equal(row.endsAt,input.endsAt);assert.deepEqual(row.providerIds,[])
  assert.equal((await getBooking(db,own,row.id)).id,row.id)
  await assert.rejects(()=>getBooking(db,{...own,userId:crypto.randomUUID()},row.id),{status:404})
  const {readAvailability}=require('../src/modules/appointments/queries')
  const slots=await readAvailability(db,own,{productId:f.productId,from:input.startsAt,to:input.endsAt,providerIds:[],resourceIds:[]})
  assert.deepEqual(slots,[])
}))
test('duración editable y reprogramación usan snapshot con rollback de conflictos',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  await seedAgenda({db,scope,fixtures:f})
  await db.serviceScheduleProfile.updateMany({where:{product_id:f.productId},data:{duration_policy:'EDITABLE'}})
  const start=new Date(f.individualInput.startsAt).getTime()
  const row=await app.createBooking(db,scope,{...f.individualInput,endsAt:new Date(start+90*60000).toISOString()})
  assert.equal(row.endsAt,new Date(start+90*60000).toISOString())
  await assert.rejects(()=>app.createBooking(db,scope,{...f.individualInput,startsAt:new Date(start+75*60000).toISOString(),idempotencyKey:crypto.randomUUID()}),{code:'SLOT_UNAVAILABLE'})
  await db.serviceScheduleProfile.updateMany({where:{product_id:f.productId},data:{enabled:false,duration_policy:'FIXED',duration_minutes:30}})
  const moved=await app.rescheduleBooking(db,scope,row.id,{startsAt:new Date(start+3*86400000).toISOString(),endsAt:new Date(start+3*86400000+120*60000).toISOString(),timezone:row.timezone,providerIds:row.providerIds,resourceIds:[],expectedVersion:row.version,reason:'Cambio',idempotencyKey:crypto.randomUUID()})
  assert.equal(new Date(moved.endsAt)-new Date(moved.startsAt),120*60000)
  assert.equal(await db.appointmentBooking.count({where:{session_id:row.sessionId}}),1)
}))
