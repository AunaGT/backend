const test=require('node:test'),assert=require('node:assert/strict'),{randomUUID}=require('node:crypto'),{readFileSync}=require('node:fs'),{join}=require('node:path')
test('document versions are opaque random revisions, not timestamps or hashes of private data',()=>{
 const {formatDocumentVersion}=require('../src/modules/integrations/draftDocument')
 const revision=randomUUID()
 assert.equal(formatDocumentVersion(revision.toUpperCase()),'auna-draft-v1:'+revision)
 assert.notEqual(formatDocumentVersion(revision),formatDocumentVersion(randomUUID()))
 for(const invalid of [null,undefined,'','2026-10-26',{},'not-a-uuid'])assert.throws(()=>formatDocumentVersion(invalid))
})
test('additive mutation schema preserves grants and receipts with tenant FKs and bounded persistent receipts',()=>{
 const sql=readFileSync(join(__dirname,'../prisma/migrations/20261026100000_integration_draft_mutations/migration.sql'),'utf8')
 assert.match(sql,/ALTER TABLE public\.commercial_documents ADD COLUMN integration_revision UUID NOT NULL DEFAULT gen_random_uuid\(\)/)
 assert.match(sql,/UNIQUE\(company_id,integration_id,document_id,action,request_key\)/)
 assert.match(sql,/REFERENCES public\.integration_credentials\(company_id,integration_id,id\)/)
 assert.match(sql,/REFERENCES public\.integration_draft_operations\(company_id,integration_id,document_id\)/)
 assert.match(sql,/REFERENCES public\.commercial_documents\(branch_id,id\) ON DELETE RESTRICT ON UPDATE CASCADE/)
 assert.match(sql,/octet_length\(receipt::text\)<=4096/)
 assert.match(sql,/ALTER TABLE public\.integration_draft_mutations ENABLE ROW LEVEL SECURITY/)
 for(const action of ['PAUSE','RESUME','UPDATE_DRAFT','CANCEL_DRAFT'])assert.ok(sql.includes(`'${action}'`))
 assert.doesNotMatch(sql,/UPDATE public\.integration_(?:credentials|draft_operations)|DELETE FROM|DROP TABLE|SECURITY DEFINER|CREATE POLICY|\bEXECUTE\s+(?!FUNCTION)/i)
 // Actual trigger behavior/locks/rollback must also be exercised in isolated PostgreSQL.
 for(const table of ['commercial_document_lines','stock_reservations','commercial_document_sales','order_deliveries','order_delivery_lines','appointment_engagements','appointment_engagement_lines'])assert.match(sql,new RegExp(`BEFORE INSERT OR UPDATE OR DELETE ON public\\.${table}`))
})
