const test = require('node:test'), assert = require('node:assert/strict')
const { createHash } = require('node:crypto')
const { createServer } = require('node:http')
const { mkdtemp, writeFile, rm, rmdir } = require('node:fs/promises')
const { tmpdir } = require('node:os')
const { join } = require('node:path')
const { supervise, isolationArgs, checkXmlRuntime } = require('../src/modules/fiscal/infile/validationChild')
const { buildLocalIssueXml, validateAndMatchXml } = require('../src/modules/fiscal/infile/xml')
const { localInput } = require('./fixtures/fiscal/local-input.cjs')
const approved = process.env.AUNA_FISCAL_XML_LOCAL_TESTS === 'approved'

test('real native XML runtime stays isolated and local-only', { skip: !approved }, async t => {
  const runtime = await checkXmlRuntime()
  assert.equal(runtime.memoryLimitBytes, 134217728); assert.equal(runtime.externalSendingAllowed, false)
  await t.test('matches generated bytes but never claims schema validation or certification', async () => {
    const input = localInput(), xml = buildLocalIssueXml(input)
    const result = await validateAndMatchXml(xml, { kind: 'LOCAL_ISSUE', input })
    assert.equal(result.matched, true); assert.equal(result.schemaValidated, false); assert.equal(result.certified, false)
    assert.equal(result.sha256, createHash('sha256').update(xml).digest('hex'))
  })
  await t.test('mutation during asynchronous validation cannot change the evidence fingerprint', async () => {
    const input = localInput(), xml = buildLocalIssueXml(input), originalHash = createHash('sha256').update(xml).digest('hex')
    const pending = validateAndMatchXml(xml, { kind: 'LOCAL_ISSUE', input })
    const offset = xml.indexOf(Buffer.from('<a:Total>112.00</a:Total>'))
    assert.ok(offset >= 0)
    xml.write('<a:Total>999.00</a:Total>', offset)
    const result = await pending
    assert.equal(result.sha256, originalHash)
    assert.notEqual(result.sha256, createHash('sha256').update(xml).digest('hex'))
    await assert.rejects(validateAndMatchXml(xml, { kind: 'LOCAL_ISSUE', input }), error => error.code === 'FISCAL_XML_MISMATCH')
  })
  await t.test('namespace spoofing, duplicate protected nodes and altered amounts cannot match', async () => {
    const input = localInput(), source = buildLocalIssueXml(input).toString()
    for (const changed of [source.replace('urn:auna:fiscal:local-draft:1', 'urn:fake'), source.replace('</a:Totals>', '<a:Total>112.00</a:Total></a:Totals>'), source.replace('<a:Total>112.00</a:Total>', '<a:Total>111.00</a:Total>'), source.replace('</a:Lines>', '<a:Line></a:Lines>')]) {
      await assert.rejects(validateAndMatchXml(Buffer.from(changed), { kind: 'LOCAL_ISSUE', input }), error => ['FISCAL_XML_MISMATCH', 'FISCAL_XML_INVALID'].includes(error.code))
    }
  })
  await t.test('actual sandbox denies private files and host network and enforces the native memory limit', async () => {
    const dir = await mkdtemp(join(tmpdir(), 'auna-xml-canary-')), file = join(dir, 'canary')
    await writeFile(file, 'SYNTHETIC_XML_CANARY_ONLY')
    let requests = 0
    const server = createServer((_req, res) => { requests++; res.end('canary') })
    await new Promise(resolve => server.listen(0, '127.0.0.1', resolve))
    const url = `http://127.0.0.1:${server.address().port}/canary`
    try {
      assert.equal(await (await fetch(url)).text(), 'canary')
      // Use the production boundary, adding only fixed diagnostic executables.
      const args = isolationArgs('probe'), separator = args.indexOf('--')
      args.splice(separator, 0, ...['sh', 'grep', 'curl'].flatMap(name => ['--ro-bind', `/usr/bin/${name}`, `/usr/bin/${name}`]))
      args.splice(args.lastIndexOf('/usr/bin/xmllint'), 2, '/usr/bin/sh', '-c', 'test ! -r "$1" && /usr/bin/curl --version >/dev/null && ! /usr/bin/curl --silent --max-time 1 "$2" && /usr/bin/grep -E "Max address space[[:space:]]+134217728[[:space:]]+134217728" /proc/self/limits', 'probe', file, url)
      const out = await supervise('/usr/bin/bwrap', args)
      assert.match(out.toString(), /Max address space\s+134217728\s+134217728/)
      assert.equal(requests, 1)
    } finally { server.closeAllConnections(); await new Promise(resolve => server.close(resolve)); await rm(file); await rmdir(dir) }
  })
})
