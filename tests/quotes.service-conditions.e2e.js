const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto')
const {withAppointmentsTestDb,seedAgenda}=require('./helpers/appointmentsTestDb.cjs')
const {withMocks,jsonResponse}=require('./helpers/reportHarness.cjs')
test('quote creation captures conditions with Agenda disabled and sent/public documents never reread profiles',async()=>withAppointmentsTestDb(async context=>{
  const {db,scope,fixtures:f}=context
  await seedAgenda(context)
  await db.serviceScheduleProfile.update({where:{product_id:f.productId},data:{public_instructions:'Acceso QA',instructions:'SECRETO_QA'}})
  await db.companyModule.updateMany({where:{company_id:scope.companyId,module_code:'appointments'},data:{status:'DISABLED'}})
  const req={companyId:scope.companyId,branchId:scope.branchId,userBranchIds:scope.branchIds,user:{sub:scope.userId,role_name:'admin'},body:{customer_contact_id:f.contactId,valid_until:'2030-01-01',items:[{product_id:f.productId,qty:1,unit_price:100},{product_id:f.productId,qty:1,unit_price:50}]}}
  const controller=require.resolve('../src/modules/quotes/controller')
  await withMocks({[require.resolve('../src/models/prisma')]:{prisma:db,prismaTransaction:db},
    [require.resolve('../src/modules/quotes/access')]:{getCompanyModuleBlock:async()=>null}},controller,async api=>{
    const res=jsonResponse();await api.create(req,res,e=>{throw e})
    assert.equal(res.statusCode,201)
    assert.equal(res.body.lines.length,2)
    for(const line of res.body.lines) assert.equal(line.service_schedule_snapshot.publicInstructions,'Acceso QA')
    assert.equal(res.body.total.toFixed(2),'150.00')
    await db.serviceScheduleProfile.update({where:{product_id:f.productId},data:{enabled:false,public_instructions:'OTRA_QA'}})
    await db.commercialDocument.update({where:{id:res.body.id},data:{status:'SENT',public_token:'qa-frozen'}})
    const shown=jsonResponse();await api.getPublicByToken({params:{token:'qa-frozen'}},shown,e=>{throw e})
    assert.equal(shown.body.lines[0].service_schedule_snapshot.publicInstructions,'Acceso QA')
    assert.ok(!JSON.stringify(shown.body).includes('SECRETO_QA'))
    assert.ok(!JSON.stringify(shown.body).includes('OTRA_QA'))
    assert.equal(await db.sale.count(),0)
    const preview=jsonResponse()
    assert.equal(typeof api.previewServiceConditions,'function')
    await api.previewServiceConditions({...req,body:{productIds:[f.productId,crypto.randomUUID()]}},preview,e=>{throw e})
    assert.equal(Object.keys(preview.body.conditions).length,1)
    assert.equal(preview.body.conditions[f.productId].publicInstructions,'OTRA_QA')
    assert.ok(!JSON.stringify(preview.body).includes('SECRETO_QA'))
  })
}))
test('commercial quote source requires accepted quote and registered contact in the active tenant/branch',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  const {loadQuoteSource}=require('../src/modules/quotes')
  const quote=await db.commercialDocument.create({data:{branch_id:scope.branchId,doc_type:'QUOTE',status:'ACCEPTED',customer_contact_id:f.contactId,total:150,
    lines:{create:{product_id:f.productId,item_kind:'SERVICE',item_name:'Servicio cotizado',unit_label:'Sesión',qty:1,unit_price:150,line_total:150}}}})
  const source=await db.$transaction(tx=>loadQuoteSource(tx,scope,quote.id))
  assert.equal(source.total,'150.00');assert.equal(source.currencyCode,'GTQ')
  assert.equal(source.lines[0].quantity,'1.0000');assert.equal(source.lines[0].serviceConditions,null)
  await assert.rejects(()=>db.$transaction(tx=>loadQuoteSource(tx,{...scope,branchId:f.secondBranchId},quote.id)),{status:404})
  await db.commercialDocument.update({where:{id:quote.id},data:{status:'SENT'}})
  await assert.rejects(()=>db.$transaction(tx=>loadQuoteSource(tx,scope,quote.id)),{code:'QUOTE_NOT_ACCEPTED'})
  await db.commercialDocument.update({where:{id:quote.id},data:{status:'ACCEPTED',customer_contact_id:null}})
  await assert.rejects(()=>db.$transaction(tx=>loadQuoteSource(tx,scope,quote.id)),{code:'CONTACT_REQUIRED'})
}))
