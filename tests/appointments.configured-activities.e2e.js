const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto')
const {withAppointmentsTestDb,seedAgenda}=require('./helpers/appointmentsTestDb.cjs')
const {activityInput}=require('./helpers/agendaActivityFixture.cjs')
const {createActivity,updateActivity}=require('../src/modules/appointments/activities')
async function setup(db,scope,f){
  await seedAgenda({db,scope,fixtures:f})
  await db.serviceScheduleProfile.updateMany({where:{product_id:f.productId},data:{scheduling_style:'WORK',duration_policy:'EDITABLE',requires_provider:false,requires_resource:false}})
  const startsAt=new Date(new Date(f.individualInput.startsAt).getTime()+3*86400000).toISOString()
  return activityInput(f,{purpose:'EVENT',title:'Show QA',productId:f.productId,serviceScheduling:'CONFIGURED',startsAt,
    endsAt:new Date(new Date(startsAt).getTime()+60*60000).toISOString(),estimatedAttendance:80})
}
test('show de catálogo ocupa un bloque con snapshot sin inscripciones ni venta',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  const input=await setup(db,scope,f),bookings=await db.appointmentBooking.count(),sales=await db.sale.count()
  const row=await createActivity(db,scope,input)
  assert.equal((await createActivity(db,scope,input)).id,row.id)
  assert.equal(row.schedulingPolicy.schedulingStyle,'WORK');assert.equal(row.estimatedAttendance,80)
  assert.equal(await db.appointmentBooking.count(),bookings);assert.equal(await db.sale.count(),sales)
  await db.companyModule.create({data:{company_id:scope.companyId,module_code:'inventory',status:'DISABLED'}})
  const moved=await updateActivity(db,scope,row.id,{...input,endsAt:new Date(new Date(input.startsAt).getTime()+90*60000).toISOString(),expectedVersion:row.version,reason:'Ampliar',idempotencyKey:crypto.randomUUID()})
  assert.equal(new Date(moved.endsAt)-new Date(moved.startsAt),90*60000)
  await assert.rejects(()=>updateActivity(db,scope,row.id,{...input,productId:null,serviceScheduling:undefined,expectedVersion:moved.version,reason:'Quitar reglas',idempotencyKey:crypto.randomUUID()}),{status:400})
}))
test('WORK no elude requisitos, perfil de otro tipo ni preparación',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  const input=await setup(db,scope,f),count=await db.appointmentSession.count()
  await assert.rejects(()=>createActivity(db,scope,{...input,serviceScheduling:undefined}),{status:400})
  await assert.rejects(()=>createActivity(db,scope,{...input,setupMinutes:20}),{status:400})
  await db.serviceScheduleProfile.updateMany({where:{product_id:f.productId},data:{requires_provider:true}})
  await assert.rejects(()=>createActivity(db,scope,input),e=>!!e.fields?.providerIds)
  await assert.rejects(()=>createActivity(db,scope,{...input,productId:f.groupProductId}),{status:400})
  assert.equal(await db.appointmentSession.count(),count)
}))
test('editar datos de un trabajo ya agendado no reaplica anticipación de creación',async()=>withAppointmentsTestDb(async({db,scope,fixtures:f})=>{
  const input=await setup(db,scope,f)
  await db.serviceScheduleProfile.updateMany({where:{product_id:f.productId},data:{lead_minutes:120}})
  const row=await createActivity(db,scope,input)
  const startsAt=new Date(Date.now()+30*60000),endsAt=new Date(startsAt.getTime()+60*60000)
  await db.appointmentSession.update({where:{id:row.id},data:{starts_at:startsAt,ends_at:endsAt,occupied_from:startsAt,occupied_until:endsAt}})
  const updated=await updateActivity(db,scope,row.id,{...input,startsAt:startsAt.toISOString(),endsAt:endsAt.toISOString(),title:'Referencia actualizada',expectedVersion:row.version,reason:'Corregir título',idempotencyKey:crypto.randomUUID()})
  assert.equal(updated.title,'Referencia actualizada')
}))
