const test=require('node:test'),assert=require('node:assert/strict'),sharp=require('sharp')
const {normalizeImage}=require('../src/modules/config/documentTemplates/assets')
const {uploadAsset,readAsset}=require('../src/modules/config/documentTemplates/assets')
const {templateDb}=require('./helpers/documentTemplateHarness.cjs')
const {saveDraft}=require('../src/modules/config/documentTemplates/service')
const {resolveBase}=require('../src/modules/config/documentTemplates/public')
const scope={companyId:'11111111-1111-4111-8111-111111111111',actorId:'22222222-2222-4222-8222-222222222222',permissions:['document_templates.manage']}
test('image content, not the claimed MIME, determines whether upload is allowed',async()=>{
  const buffer=await sharp({create:{width:20,height:20,channels:3,background:'#fff'}}).png().toBuffer()
  const normalized=await normalizeImage({buffer,mimetype:'image/png'})
  assert.equal(normalized.width,20);assert.equal((await sharp(normalized.buffer).metadata()).format,'png')
  await assert.rejects(normalizeImage({buffer,mimetype:'image/jpeg'}),{status:400})
  await assert.rejects(normalizeImage({buffer:Buffer.from('<svg/>'),mimetype:'image/png'}),{status:400})
  await assert.rejects(normalizeImage({buffer:Buffer.alloc(5*1024*1024+1),mimetype:'image/png'}),{status:413})
})
test('oversized pixel dimensions are rejected; accepted images are bounded and stripped of metadata',async()=>{
  const huge=await sharp({create:{width:5000,height:4100,channels:3,background:'#fff'}}).png().toBuffer()
  await assert.rejects(normalizeImage({buffer:huge,mimetype:'image/png'}),{status:400})
  const big=await sharp({create:{width:2500,height:1000,channels:3,background:'#fff'}}).jpeg().toBuffer()
  const image=await normalizeImage({buffer:big,mimetype:'image/jpeg'})
  assert.equal(image.width,2400);assert.equal(image.height,960)
  assert.equal((await sharp(image.buffer).metadata()).exif,undefined)
})
test('images attach only to the current author draft, respect five slots and reject stale revisions',async()=>{
  const db=templateDb(),draft=await saveDraft(db,scope,{expectedVersion:0,name:'Imágenes',design:resolveBase(),requestKey:'new'})
  const buffer=await sharp({create:{width:1,height:1,channels:3,background:'#fff'}}).png().toBuffer(),file={buffer,mimetype:'image/png'}
  const paths=[],removed=[],getStore=async()=>({upload:async path=>{paths.push(path);return {data:{path}}},remove:async paths=>{removed.push(...paths);return {data:[]}}})
  const result=await uploadAsset(db,scope,{versionId:draft.versionId,slot:'imagen-1',expectedVersion:1,file},{getStore})
  assert.equal(result.version,2);assert.equal(db.state.versions[0].resource_refs['imagen-1'],result.id)
  await assert.rejects(uploadAsset(db,scope,{versionId:draft.versionId,slot:'imagen-6',expectedVersion:2,file},{getStore}),{status:400})
  await assert.rejects(uploadAsset(db,{...scope,actorId:'33333333-3333-4333-8333-333333333333'},{versionId:draft.versionId,slot:'imagen-2',expectedVersion:2,file},{getStore}),{status:404})
  await assert.rejects(uploadAsset(db,scope,{versionId:draft.versionId,slot:'imagen-2',expectedVersion:1,file},{getStore}),{status:409})
  assert.equal(removed.length,1);assert.equal(db.state.assets.length,1)
  await assert.rejects(readAsset(db,{...scope,companyId:'33333333-3333-4333-8333-333333333333'},result.id),{status:404})
})
