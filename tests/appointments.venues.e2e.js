const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto')
const {withAppointmentsTestDb,seedAgenda}=require('./helpers/appointmentsTestDb.cjs')
const {activityInput}=require('./helpers/agendaActivityFixture.cjs')
test('show externo usa horario propio; sala, equipo fijo y capacidad se revalidan',async()=>withAppointmentsTestDb(async context=>{
  await seedAgenda(context)
  const {db,scope,fixtures:f}=context,{saveCalendar}=require('../src/modules/appointments/calendars')
  const {createActivity}=require('../src/modules/appointments/activities')
  const branch=await db.scheduleCalendar.findUnique({where:{branch_id:scope.branchId}})
  await db.availabilityRule.deleteMany({where:{calendar_id:branch.id}})
  const provider=await db.scheduleCalendar.findUnique({where:{provider_id:f.providerId}})
  await saveCalendar(db,scope,'provider',f.providerId,{timezone:'America/Guatemala',expectedVersion:provider.version,inheritBranch:false,
    weekly:Array.from({length:7},(_,i)=>({weekday:i+1,from:'00:00',to:'24:00'})),exceptions:[]})
  const base=activityInput(f,{purpose:'EVENT',estimatedAttendance:80,providerIds:[f.providerId],venue:{kind:'EVENT_VENUE',address:'Salón del cliente'},outboundMinutes:30,setupMinutes:60,returnMinutes:30})
  await assert.rejects(()=>createActivity(db,scope,{...base,resourceIds:[f.resourceId]}),{code:'RESOURCE_NOT_PORTABLE'})
  await assert.rejects(()=>createActivity(db,scope,{...base,venue:{kind:'BRANCH'},resourceIds:[f.resourceId]}),{code:'ROOM_CAPACITY'})
  const equipment=await db.scheduleResource.create({data:{company_id:scope.companyId,branch_id:scope.branchId,name:'Sonido',type:'EQUIPMENT',portable:true}})
  const row=await createActivity(db,scope,{...base,resourceIds:[equipment.id]})
  assert.equal(row.estimatedAttendance,80);assert.equal(await db.appointmentBooking.count({where:{session_id:row.id}}),0)
  assert.equal(new Date(row.startsAt)-new Date(row.occupiedFrom),90*60000)
  await assert.rejects(()=>db.scheduleResource.update({where:{id:f.resourceId},data:{portable:true}}))
}))
test('servicio exterior exige autorización del perfil y conserva márgenes en snapshot',async()=>withAppointmentsTestDb(async context=>{
  await seedAgenda(context)
  const {db,scope,fixtures:f}=context,app=require('../src/modules/appointments/application')
  const input={...f.individualInput,venue:{kind:'HOME',address:'Casa del cliente'},outboundMinutes:30,returnMinutes:45}
  await assert.rejects(()=>app.createBooking(db,scope,input),{code:'VENUE_NOT_ALLOWED'})
  await db.serviceScheduleProfile.update({where:{product_id:f.productId},data:{allowed_venue_kinds:['BRANCH','HOME'],before_minutes:15,after_minutes:20}})
  const row=await app.createBooking(db,scope,{...input,idempotencyKey:crypto.randomUUID()})
  const session=await db.appointmentSession.findUnique({where:{id:row.sessionId}})
  assert.equal(session.venue.kind,'HOME');assert.equal(session.setup_minutes,15)
  assert.equal(session.starts_at-session.occupied_from,45*60000)
  assert.equal(session.occupied_until-session.ends_at,65*60000)
}))
