const test = require('node:test')
const assert = require('node:assert/strict')
const { randomUUID } = require('node:crypto')
const { spawnSync } = require('node:child_process')
const { PrismaClient } = require('@prisma/client')
const { servicesTestDatabaseUrl, openServicesTestDb } = require('./helpers/servicesTestDb.cjs')
const { withMocks, jsonResponse } = require('./helpers/reportHarness.cjs')

const enabled = Boolean(process.env.AUNA_SERVICES_TEST_DATABASE_URL || process.env.AUNA_SERVICES_STAGING_TESTS === 'approved')
test('real isolated services: tenant guard, historic snapshots and concurrent delivery/invoice/refund balances', { skip: !enabled, timeout: 180000 }, async t => {
  require('../src/config/loadEnv')
  const schema = 'services_' + randomUUID().replaceAll('-', '')
  assert.match(schema, /^services_[a-f0-9]{32}$/)
  const control = openServicesTestDb()
  const url = new URL(servicesTestDatabaseUrl())
  url.searchParams.set('schema', schema)
  url.searchParams.set('connection_limit', '1')
  url.searchParams.set('pool_timeout', '30')
  const clients = [0, 1].map(() => new PrismaClient({ datasources: { db: { url: url.toString() } } }))
  const [db, other] = clients
  const started = Date.now()
  try {
    await control.$executeRawUnsafe(`CREATE SCHEMA "${schema}"`)
    const pushed = spawnSync(process.execPath, ['node_modules/prisma/build/index.js', 'db', 'push', '--skip-generate'], {
      cwd: require('node:path').resolve(__dirname, '..'), env: { ...process.env, DATABASE_URL: url.toString(), DIRECT_URL: url.toString() }, encoding: 'utf8', timeout: 90000,
    })
    assert.equal(pushed.status, 0, 'Could not prepare the isolated Prisma schema')
    assert.equal((await db.$queryRaw`SELECT current_schema() AS name`)[0].name, schema)
    assert.equal(await db.company.count(), 0, 'Never run fixtures in public')
    const company = await db.company.create({ data: { name: 'Servicios QA', code: 'SERV-QA' } })
    const foreign = await db.company.create({ data: { name: 'Empresa B', code: 'SERV-B' } })
    const branch = await db.branch.create({ data: { company_id: company.id, name: 'Principal QA', code: 'QA' } })
    const role = await db.role.create({ data: { name: 'admin' } })
    const user = await db.user.create({ data: { name: 'QA', email: 'qa@services.invalid', password: 'not-a-login', role_id: role.id } })
    const category = await db.productCategory.create({ data: { company_id: company.id, name: 'Servicios' } })
    const stockStatus = await db.stockStatus.create({ data: { name: 'Disponible' } })
    const completed = await db.saleStatus.create({ data: { name: 'Completada' } })
    for (const name of ['Pendiente', 'Aprobada', 'Completada', 'Rechazada']) await db.returnStatus.create({ data: { name } })
    const method = await db.paymentMethod.create({ data: { name: 'Efectivo' } })
    const register = await db.cashRegister.create({ data: { branch_id: branch.id, name: 'Caja QA', code: 'QA', is_default: true } })
    const session = await db.cashRegisterSession.create({ data: { cash_register_id: register.id, opened_by_id: user.id, opening_float: 0 } })
    await db.systemSetting.create({ data: { company_id: company.id, key: 'inventory_services_enabled', value: 'true' } })
    const req = { companyId: company.id, branchId: branch.id, branchIds: [branch.id], userBranchIds: [branch.id], user: { sub: user.id, role: { name: 'admin' } }, query: {} }
    const model = require.resolve('../src/models/prisma')
    const load = (module, client = db) => withMocks({ [model]: { prisma: client, prismaTransaction: client } }, require.resolve(module), controller => controller)
    async function call(controller, action, request) {
      const res = jsonResponse()
      await controller[action](request, res, error => { throw error })
      if (res.statusCode >= 400) throw Object.assign(new Error(res.body.message), { status: res.statusCode })
      return res.body
    }
    const products = await load('../src/modules/inventory/products.controller')
    const payload = { name: 'Asesoría original', kind: 'SERVICE', category_id: category.id, service_unit_label: 'Hora', quantity_decimals: 2, price: '100' }
    const {product: service} = await call(products, 'create', { ...req, body: payload })
    assert.equal(service.kind, 'SERVICE')
    await assert.rejects(call(products, 'create', { ...req, companyId: foreign.id, body: payload }), error => error.status === 403)
    const orders = await load('../src/modules/orders/controller')
    const ordersOther = await load('../src/modules/orders/controller', other)
    const goods=await db.product.create({data:{company_id:company.id,name:'Bien legacy',kind:'STANDARD',category_id:category.id,status_id:stockStatus.id,cost:30,price:50}})
    await db.productStock.create({data:{product_id:goods.id,branch_id:branch.id,stock:10}})
    const quotes=await load('../src/modules/quotes/controller')
    const quote=await call(quotes,'create',{...req,body:{customer:'Cliente QA',items:[{product_id:service.id,qty:'2.5',unit_price:100},{product_id:goods.id,qty:2,unit_price:50}]}})
    await call(quotes,'updateStatus',{...req,params:{id:quote.id},body:{status:'SENT'}})
    await call(quotes,'updateStatus',{...req,params:{id:quote.id},body:{status:'ACCEPTED'}})
    await db.product.update({ where: { id: service.id }, data: { name: 'Nombre editado', service_unit_label: 'Sesión', quantity_decimals: 0 } })
    const converted=await call(quotes,'convertToOrder',{...req,params:{id:quote.id},body:{}})
    const order=converted.order ?? converted
    await call(orders,'confirm',{...req,params:{id:order.id},body:{}})
    const serviceLine=order.lines.find(line=>line.item_kind==='SERVICE')
    assert.equal(serviceLine.unit_label,'Hora')
    assert.equal(await db.stockReservation.count({where:{product_id:service.id}}),0)
    await db.systemSetting.update({ where: { company_id_key: { company_id: company.id, key: 'inventory_services_enabled' } }, data: { value: 'false' } })
    const attempt = controller => ({ controller, request: { ...req, params: { id: order.id }, body: { request_key: randomUUID(), lines: [{ line_id: serviceLine.id, qty: '1.5' }] } } })
    const attempts = [attempt(orders), attempt(ordersOther)]
    const delivered = await Promise.allSettled(attempts.map(({ controller, request }) => call(controller, 'deliver', request)))
    assert.equal(delivered.filter(row => row.status === 'fulfilled').length, 1)
    assert.equal((await db.commercialDocumentLine.findUnique({ where: { id: serviceLine.id } })).qty_fulfilled.toString(), '1.5')
    const winner = delivered.findIndex(row => row.status === 'fulfilled')
    assert.equal((await call(attempts[winner].controller, 'deliver', attempts[winner].request)).delivery.id, delivered[winner].value.delivery.id)
    assert.equal(await db.orderDelivery.count(), 1)
    const invoiceRequest = () => ({ ...req, params: { id: order.id }, body: { request_key: randomUUID(), payment_method_id: method.id, cash_register_id: register.id, lines: [{ line_id: serviceLine.id, qty: '1.25' }] } })
    await db.cashRegisterSession.update({where:{id:session.id},data:{status:'CLOSED'}})
    await assert.rejects(call(orders,'invoice',{...invoiceRequest(),user:{sub:user.id,role:{name:'vendedor'}}}),/CASH|turno|caja/i)
    assert.equal(await db.sale.count(),0)
    await db.cashRegisterSession.update({where:{id:session.id},data:{status:'OPEN'}})
    const invoiceRequests = [invoiceRequest(), invoiceRequest()]
    const invoices = await Promise.allSettled([call(orders, 'invoice', invoiceRequests[0]), call(ordersOther, 'invoice', invoiceRequests[1])])
    assert.equal(invoices.filter(row => row.status === 'fulfilled').length, 1)
    const invoiceWinner = invoices.findIndex(row => row.status === 'fulfilled')
    const sale = invoices[invoiceWinner].value.sale
    assert.equal(sale.items, 0)
    assert.equal(String(sale.total), '125')
    assert.equal(sale.cash_register_session_id, session.id)
    assert.equal((await call(invoiceWinner ? ordersOther : orders, 'invoice', invoiceRequests[invoiceWinner])).sale.id, sale.id)
    const billed = await db.saleItem.findFirst({ where: { sale_id: sale.id } })
    assert.equal(billed.unit_label, 'Hora')
    assert.equal(billed.item_name, 'Asesoría original')
    assert.equal(billed.qty.toString(), '1.25')
    const returns = await load('../src/modules/returns/controller')
    const returnsOther = await load('../src/modules/returns/controller', other)
    const refundRequest = () => ({ ...req, body: { sale_id: sale.id, reason: 'Prueba de saldo concurrente', items: [{ sale_item_id: billed.id, product_id: service.id, qty_returned: '1' }] } })
    const refunds = await Promise.allSettled([call(returns, 'create', refundRequest()), call(returnsOther, 'create', refundRequest())])
    assert.equal(refunds.filter(row => row.status === 'fulfilled').length, 1)
    assert.equal(await db.return.count(), 1)
    assert.equal((await db.returnItem.findFirst()).qty_returned.toString(), '1')
    const refund=await db.return.findFirst({include:{return_items:true}})
    const remainder=await call(returns,'create',{...req,body:{sale_id:sale.id,reason:'Segundo reembolso',items:[{sale_item_id:billed.id,product_id:service.id,qty_returned:'0.25'}]}})
    const secondRefund=await db.return.findUnique({where:{id:remainder.id},include:{return_items:true}})
    const {approveReturn,completeReturn}=require('../src/modules/returns/application')
    const scope={branch_id:branch.id}
    await db.$transaction(tx=>approveReturn(tx,{id:refund.id,scope,userId:user.id,companyId:company.id,resolution:'REFUND_ORIGINAL',lines:[{return_item_id:refund.return_items[0].id}],policy:{enabledResolutions:['REFUND_ORIGINAL']}}),{timeout:30000})
    await db.$transaction(tx=>approveReturn(tx,{id:secondRefund.id,scope,userId:user.id,companyId:company.id,resolution:'REFUND_ORIGINAL',lines:[{return_item_id:secondRefund.return_items[0].id}],policy:{enabledResolutions:['REFUND_ORIGINAL']}}),{timeout:30000})
    const settlement={id:refund.id,scope,userId:user.id,companyId:company.id,payload:{idempotency_key:randomUUID(),lines:[{return_item_id:refund.return_items[0].id}],settlement:{payment_method_id:method.id,cash_register_session_id:session.id}}}
    await Promise.all([completeReturn(db,settlement),completeReturn(other,{...settlement,id:secondRefund.id,payload:{...settlement.payload,idempotency_key:randomUUID(),lines:[{return_item_id:secondRefund.return_items[0].id}]}})])
    assert.equal((await completeReturn(db,settlement))._idempotent,true)
    assert.equal((await db.sale.findUnique({where:{id:sale.id}})).adjusted_total.toString(),'0')
    assert.equal((await db.sale.findUnique({where:{id:sale.id}})).total_returned.toString(),'125')
    assert.equal((await db.returnItem.findFirst()).restock_qty,null)
    const {DEFAULT_ACCOUNT_KEYS}=require('../src/services/accounting/core')
    const map={}
    for(const [i,key] of DEFAULT_ACCOUNT_KEYS.entries()){
      map[key]=String(1000+i)
      await db.account.create({data:{company_id:company.id,code:map[key],name:key,type:'ASSET'}})
    }
    await db.systemSetting.createMany({data:[{company_id:company.id,key:'accounting.defaultAccounts',value:JSON.stringify(map)},{company_id:company.id,key:'vat_affiliation',value:'Pequeño contribuyente'},{company_id:company.id,key:'pequeno_rate',value:'0'}]})
    const {postPendingOperations}=require('../src/services/accounting/postingEngine')
    await postPendingOperations(db,user.id,company.id)
    const entries=await db.journalEntry.findMany({where:{company_id:company.id},include:{lines:{include:{account:true}}}})
    assert.equal(entries.length,3)
    for(const entry of entries){
      assert.equal(entry.lines.reduce((sum,line)=>sum+Number(line.debit)-Number(line.credit),0),0)
      assert.equal(entry.lines.some(line=>['inventory','cogs'].includes(line.account.name)),false)
    }
    await postPendingOperations(db,user.id,company.id)
    assert.equal(await db.journalEntry.count(),3)
    const reports=await load('../src/modules/reports/controller')
    const result=await reports.getFinancialData(null,null,{...req,reportPeriod:{start:null,endExclusive:null}})
    assert.equal(result.totalServiceRevenue,0)
    assert.equal(result.totalCost,0)
    assert.equal(result.quantitiesByUnit.find(row=>row.unit==='Hora').quantity,'1.25')
    assert.equal(await db.productStock.count({where:{product_id:service.id}}), 0)
    assert.equal(await db.productStockLocation.count({where:{product_id:service.id}}), 0)
    assert.equal(await db.productLot.count({where:{product_id:service.id}}), 0)
    assert.equal(await db.stockReservation.count({where:{product_id:service.id}}), 0)
    assert.equal(await db.sale.count({ where: { status_id: completed.id } }), 1)
    t.diagnostic(`Real delivery/invoice/refund concurrency and retry checks completed in ${Date.now() - started}ms; public data untouched`)
  } finally {
    await Promise.all(clients.map(client => client.$disconnect()))
    await control.$executeRawUnsafe(`DROP SCHEMA IF EXISTS "${schema}" CASCADE`)
    await control.$disconnect()
  }
})
