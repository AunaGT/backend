const test = require('node:test'), assert = require('node:assert/strict'), crypto = require('node:crypto')
const { withAppointmentsTestDb, seedAgenda } = require('./helpers/appointmentsTestDb.cjs')
const app = require('../src/modules/appointments/application')
const queries = require('../src/modules/appointments/queries')
const action = (name, version = 1) => ({ action: name, expectedVersion: version, idempotencyKey: crypto.randomUUID(), reason: name === 'CANCEL' ? 'Solicitud del cliente' : '' })
test('atención individual, cierre grupal sin asistencia ficticia, espera FIFO y queries seguras', async () => withAppointmentsTestDb(async context => {
  await seedAgenda(context)
  const { db, scope, fixtures: f } = context
  const created = await app.createBooking(db, scope, f.individualInput)
  await assert.rejects(() => app.transitionBooking(db, scope, created.id, action('NO_SHOW')), { status: 409, code: 'TOO_EARLY' })
  const cancelled = await app.transitionBooking(db, scope, created.id, action('CANCEL'))
  assert.equal(cancelled.status, 'CANCELLED')
  await app.createBooking(db, scope, { ...f.individualInput, idempotencyKey: crypto.randomUUID() })
  const c2 = await db.supplier.create({ data: { company_id: scope.companyId, name: 'Primero espera', contact: 'Cliente', party_type: 'CUSTOMER' } })
  const c3 = await db.supplier.create({ data: { company_id: scope.companyId, name: 'Segundo espera', contact: 'Cliente', party_type: 'CUSTOMER' } })
  const w1 = await app.joinWaitlist(db, scope, f.groupSessionId, { contactId: c2.id, idempotencyKey: crypto.randomUUID() })
  const w2 = await app.joinWaitlist(db, scope, f.groupSessionId, { contactId: c3.id, idempotencyKey: crypto.randomUUID() })
  await assert.rejects(() => app.admitWaitlist(db, scope, w2.id, { quantity: '1', idempotencyKey: crypto.randomUUID() }), { status: 409, code: 'WAITLIST_ORDER' })
  const admitted = await app.admitWaitlist(db, scope, w1.id, { quantity: '1', idempotencyKey: crypto.randomUUID() })
  assert.equal(admitted.contactId, c2.id)
  assert.equal(admitted.commercial.total, '75.00')
  await db.appointmentSession.update({ where: { id: f.groupSessionId }, data: { status: 'IN_PROGRESS' } })
  assert.equal((await app.transitionSession(db, scope, f.groupSessionId, action('COMPLETE'))).status, 'COMPLETED')
  assert.equal((await db.appointmentBooking.findUnique({ where: { id: f.confirmedBookingId } })).status, 'CONFIRMED')
  const filter = { from: f.individualInput.startsAt, to: new Date(new Date(f.individualInput.startsAt).getTime() + 259200000).toISOString(), pageSize: 1 }
  const result = await queries.listBookings(db, scope, filter)
  assert.equal(result.items.length, 1)
  assert.equal(result.totalItems, 4)
  assert.equal((await queries.readSummary(db, scope, filter)).reservations, result.totalItems)
  const own = { ...scope, isAdmin: false, permissions: ['appointments.view'] }
  assert.equal((await queries.listBookings(db, { ...own, userId: crypto.randomUUID() }, filter)).totalItems, 0)
  const hiddenMoney = await queries.getBooking(db, own, admitted.id)
  assert.equal(hiddenMoney.commercial, null); assert.equal(hiddenMoney.notes, null)
  await assert.rejects(() => queries.getBooking(db, { ...scope, branchId: f.secondBranchId }, admitted.id), { status: 404 })
  assert.equal((await queries.getSession(db, scope, f.groupSessionId)).bookings.totalItems, 2)
  assert.equal((await queries.listServices(db, scope)).totalItems, 2)
  assert.equal(await db.sale.count(), 0); assert.equal(await db.customerPayment.count(), 0); assert.equal(await db.productStock.count(), 0)
}))
