const test=require('node:test'),assert=require('node:assert/strict'),crypto=require('node:crypto')
const {devDbEnabled,withSalesDevFixture,snapshotSaleEffects}=require('./helpers/salesDevFixture.cjs')
test('draft preserves original lines, financial pointer and effects across repeat preparation',{skip:!devDbEnabled},()=>withSalesDevFixture(async({db,scope,fixtures:f})=>{
  const {createEngagement}=require('../src/modules/appointments/engagements'),{loadEngagement}=require('../src/modules/appointments/commercialQueries')
  const e=await createEngagement(db,scope,{quoteId:f.quoteId,idempotencyKey:crypto.randomUUID()})
  const before=await snapshotSaleEffects(db,scope,e.id),{ensureEngagementDraft}=require('../src/modules/sales')
  assert.equal(typeof ensureEngagementDraft,'function')
  const prepare=()=>db.$transaction(async tx=>ensureEngagementDraft(tx,scope,{source:await loadEngagement(tx,scope,e.id)}))
  const a=await prepare()
  await db.product.update({where:{id:f.productId},data:{price:999}})
  const b=await prepare()
  assert.equal(a.saleId,b.saleId)
  const sale=await db.sale.findUnique({where:{id:a.saleId},include:{sale_items:true,status:true}})
  assert.equal(sale.status.name,'Borrador');assert.equal(sale.payment_method_id,null)
  assert.equal(sale.total.toFixed(2),'175.00');assert.equal(sale.sale_items.length,3)
  assert.deepEqual(sale.sale_items.map(l=>l.price.toFixed(2)).sort(),['100.00','25.00','50.00'])
  assert.equal((await db.appointmentEngagement.findUnique({where:{id:e.id}})).sale_id,null)
  assert.deepEqual(await snapshotSaleEffects(db,scope,e.id),before)
  await assert.rejects(()=>db.sale.create({data:{branch_id:scope.branchId,origin_engagement_id:e.id,items:0,total:0,adjusted_total:0,status_id:sale.status_id}}),{code:'P2002'})
  await assert.rejects(()=>db.sale.create({data:{branch_id:f.secondBranchId,origin_engagement_id:e.id,items:0,total:0,adjusted_total:0,status_id:sale.status_id}}))
}))
