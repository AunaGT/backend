try{({issueEngagementSale}=require('../src/modules/appointments/engagementSales'))}catch(e){if(e.code!=='MODULE_NOT_FOUND')throw e}
async function servicesOnly(db,f){
  await db.commercialDocumentLine.deleteMany({where:{document_id:f.quoteId,item_kind:'STANDARD'}})
  await db.commercialDocument.update({where:{id:f.quoteId},data:{total:150,subtotal:150}})
}
test('issuing a historical quote applies its advance without another receipt, stock or current-price substitution',async()=>withCommercialAgendaTestDb(async({db,scope,fixtures:f})=>{
  assert.equal(typeof issueEngagementSale,'function')
  await db.companyModule.create({data:{company_id:scope.companyId,module_code:'accounting',status:'DISABLED'}})
  await servicesOnly(db,f)
  const e=await f.paidEngagement('40.00'),before=await db.customerPayment.count()
  const result=await issueEngagementSale(db,scope,e.id,{...f.saleTerms,expectedVersion:e.version,idempotencyKey:crypto.randomUUID()})
  assert.equal(await db.customerPayment.count(),before)
  assert.equal(result.money.applied,'40.00');assert.equal(result.money.committed,'0.00');assert.equal(result.money.remaining,'110.00')
  const sale=await db.sale.findUnique({where:{id:result.saleId},include:{sale_items:true}})
  assert.equal(sale.total.toFixed(2),'150.00');assert.equal(sale.payment_status,'PARTIAL');assert.equal(sale.settlement_source,'ENGAGEMENT_RECEIPTS')
  assert.equal(sale.amount_received,null);assert.equal(sale.cash_register_session_id,null)
  assert.deepEqual(sale.sale_items.map(l=>l.price.toFixed(2)).sort(),['100.00','50.00'])
  assert.ok(sale.sale_items.every(l=>l.unit_cost.toFixed(2)==='0.00'))
  assert.equal(await db.stockMovement.count(),0)
  assert.equal(await db.salePaymentEntry.count({where:{sale_id:f.priorSale.id}}),0)
  const again=await issueEngagementSale(db,scope,e.id,{...f.saleTerms,expectedVersion:result.version,idempotencyKey:crypto.randomUUID()})
  assert.equal(again.saleId,sale.id);assert.equal(await db.sale.count({where:{settlement_source:'ENGAGEMENT_RECEIPTS'}}),1)
}))
