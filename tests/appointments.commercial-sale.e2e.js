test('issuing posts the sale and advance reclassification atomically, and closed periods preserve the original commitment',async()=>withCommercialAgendaTestDb(async({db,scope,fixtures:f})=>{
  const accounts=await require('./helpers/commercialAgendaFixture.cjs').configureAccounting(db,scope,{full:true})
  await servicesOnly(db,f)
  const e=await f.paidEngagement('40.00')
  await db.accountingPeriod.updateMany({where:{company_id:scope.companyId},data:{status:'CLOSED'}})
  await assert.rejects(()=>issueEngagementSale(db,scope,e.id,{...f.saleTerms,expectedVersion:e.version,idempotencyKey:crypto.randomUUID()}),/cerrado/)
  assert.equal(await db.sale.count({where:{settlement_source:'ENGAGEMENT_RECEIPTS'}}),0);assert.equal(await db.salePaymentEntry.count(),0)
  assert.equal((await require('../src/modules/appointments/engagements').getEngagement(db,scope,e.id)).money.committed,'40.00')
  await db.accountingPeriod.updateMany({where:{company_id:scope.companyId},data:{status:'OPEN'}})
  const result=await issueEngagementSale(db,scope,e.id,{...f.saleTerms,expectedVersion:e.version,idempotencyKey:crypto.randomUUID()})
  const entry=await db.journalEntry.findFirst({where:{source_type:'SALE',source_id:result.saleId},include:{lines:true}})
  assert.ok(entry.lines.some(l=>l.account_id===accounts.receivables.id&&l.debit.toFixed(2)==='150.00'))
  assert.ok(!entry.lines.some(l=>[accounts.cash.id,accounts.bank.id,accounts.customerAdvances.id].includes(l.account_id)))
  assert.equal(await db.journalEntry.count({where:{source_type:'CUSTOMER_ADVANCE_APPLIED'}}),1)
  assert.equal(await db.customerPayment.count(),1)
}))
